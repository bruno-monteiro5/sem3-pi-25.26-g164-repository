package domain.railway;

import java.time.LocalDateTime;

/**
 * Represents a planned or actual train movement through an endpoint.
 * Maps to Train_Movement, Stop, and Passage tables.
 *
 */
public class TrainMovementRecord {

    public enum MovementType {
        /** Train passes through without stopping */
        PASSAGE,
        /** Train stops at the endpoint */
        STOP
    }

    private Integer id; // Generated by database
    private int trainId;
    private Endpoint endpoint;
    private MovementType type;

    // For PASSAGE
    private LocalDateTime passageTime;

    // For STOP
    private LocalDateTime arrivalTime;
    private LocalDateTime departureTime;

    // Constructor for PASSAGE
    public TrainMovementRecord(int trainId, Endpoint endpoint, LocalDateTime passageTime) {
        this.trainId = trainId;
        this.endpoint = endpoint;
        this.type = MovementType.PASSAGE;
        this.passageTime = passageTime;
    }

    // Constructor for STOP
    public TrainMovementRecord(int trainId, Endpoint endpoint,
                               LocalDateTime arrivalTime, LocalDateTime departureTime) {
        this.trainId = trainId;
        this.endpoint = endpoint;
        this.type = MovementType.STOP;
        this.arrivalTime = arrivalTime;
        this.departureTime = departureTime;
    }

    // Getters
    public Integer getId() { return id; }
    public int getTrainId() { return trainId; }
    public Endpoint getEndpoint() { return endpoint; }
    public MovementType getType() { return type; }
    public LocalDateTime getPassageTime() { return passageTime; }
    public LocalDateTime getArrivalTime() { return arrivalTime; }
    public LocalDateTime getDepartureTime() { return departureTime; }

    public void setId(Integer id) { this.id = id; }

    public boolean isStop() { return type == MovementType.STOP; }
    public boolean isPassage() { return type == MovementType.PASSAGE; }

    @Override
    public String toString() {
        if (isStop()) {
            return String.format("STOP at %s: arrive %s, depart %s",
                    endpoint.getName(),
                    arrivalTime.toLocalTime(),
                    departureTime.toLocalTime());
        } else {
            return String.format("PASSAGE at %s: %s",
                    endpoint.getName(),
                    passageTime.toLocalTime());
        }
    }
}